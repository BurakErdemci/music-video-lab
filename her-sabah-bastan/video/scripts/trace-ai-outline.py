# Traces the alpha edge of public/poses/a10-onden.png into a smooth SVG path (image pixels), written to
# src/world/aiOutline.ts. The zoom intro draws it as a vector once the raster is magnified beyond ~1.5x.
# The art's navy stroke lies INSIDE the alpha edge, so the path is stroked with a clip to its own fill.
from PIL import Image
from collections import defaultdict
src = Image.open('public/poses/a10-onden.png').convert('RGBA')
W, H = src.size
px = src.load()
on = lambda x, y: 0 <= x < W and 0 <= y < H and px[x, y][3] > 128
# directed boundary edges between grid corners, interior on the left of the direction
nxt = defaultdict(list)
for y in range(H):
    for x in range(W):
        if not on(x, y):
            continue
        if not on(x, y - 1): nxt[(x, y)].append((x + 1, y))
        if not on(x + 1, y): nxt[(x + 1, y)].append((x + 1, y + 1))
        if not on(x, y + 1): nxt[(x + 1, y + 1)].append((x, y + 1))
        if not on(x - 1, y): nxt[(x, y + 1)].append((x, y))
loops = []
while nxt:
    start = next(iter(nxt))
    loop = [start]
    cur = start
    while True:
        outs = nxt[cur]
        n = outs.pop()
        if not outs: del nxt[cur]
        cur = n
        if cur == start: break
        loop.append(cur)
        if cur not in nxt: break
    loops.append(loop)
def smooth(pts, win=9):
    n = len(pts); k = win // 2
    return [(sum(pts[(i + j) % n][0] for j in range(-k, k + 1)) / win, sum(pts[(i + j) % n][1] for j in range(-k, k + 1)) / win) for i in range(n)]
def rdp(pts, eps):
    if len(pts) < 3: return pts
    (x1, y1), (x2, y2) = pts[0], pts[-1]
    dx, dy = x2 - x1, y2 - y1
    L = (dx * dx + dy * dy) ** 0.5 or 1
    best, bi = 0, 0
    for i in range(1, len(pts) - 1):
        d = abs(dy * pts[i][0] - dx * pts[i][1] + x2 * y1 - y2 * x1) / L
        if d > best: best, bi = d, i
    if best > eps:
        a = rdp(pts[:bi + 1], eps); b = rdp(pts[bi:], eps)
        return a[:-1] + b
    return [pts[0], pts[-1]]
d = ''
for loop in loops:
    if len(loop) < 24: continue
    s = smooth(smooth(loop))
    # split the closed loop at its two farthest-apart indices so RDP has stable anchors
    h = len(s) // 2
    a = rdp(s[:h + 1], 0.18); b = rdp(s[h:] + [s[0]], 0.18)
    p = a[:-1] + b[:-1]
    d += 'M' + ' L'.join('%.1f,%.1f' % q for q in p) + ' Z '
out = '// Generated by scripts/trace-ai-outline.py from public/poses/a10-onden.png. Do not edit by hand.\nexport const AI_OUTLINE = { w: %d, h: %d, strokePx: 3.6, d: "%s" } as const;\n' % (W, H, d.strip())
open('src/world/aiOutline.ts', 'w').write(out)
print(len(loops), 'loops', len(d), 'chars')
