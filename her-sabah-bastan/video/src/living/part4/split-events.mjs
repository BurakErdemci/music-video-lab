#!/usr/bin/env node
// Splits events.json (song frames 4676-7222) into events-4a.json (Part4a) and events-4b.json (Part4b) for
// living-checks.mjs, which maps composition frame 0 to `songStart`.
//   node video/src/living/part4/split-events.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const all = JSON.parse(fs.readFileSync(path.join(HERE, 'events.json'), 'utf8'));
const split = all.splitAt;
const parts = [
  ['events-4a.json', all.songStart, split],
  ['events-4b.json', split, all.songEnd],
];
for (const [file, a, b] of parts) {
  const out = { _doc: `Generated by split-events.mjs from events.json: song frames ${a}..${b - 1}.`, songStart: a, songEnd: b, events: all.events.filter((e) => e.f >= a && e.f < b) };
  if (all.deliberateBlack) out.deliberateBlack = all.deliberateBlack.filter(([x, y]) => y >= a && x < b);
  fs.writeFileSync(path.join(HERE, file), JSON.stringify(out, null, 1) + '\n');
  console.log(`${file}: songStart ${a}, songEnd ${b}, ${out.events.length} events`);
}
