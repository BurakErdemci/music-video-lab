"""Copy the key-pose strips into video/public/strips and measure them for the Actor.

usage (repo root): python video/scripts/make-strips.py

Writes video/src/characters/stripData.ts. Each frame gets its size and a foot anchor measured from the
alpha channel (the strips are cropped to the figure, so the bottom-centre of the crop is NOT a stable
anchor: raised arms and strides change the crop width). Anchor modes:
  feet  - centre of the opaque pixels in the bottom 4% of rows (standing, sitting on a chair, kneeling)
  torso - centre of the opaque pixels in rows 30-60% (walk cycles: the hips stay put, the feet swing)
  right - the planted hands on the floor at the right edge (A02, sitting with legs out)
The AI strips also get the cursor slit (the dark vertical bar in the head), so a blink can paint over it.
"""
import json
import os
import shutil
import sys
from collections import deque

from PIL import Image

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
SRC = os.path.join(ROOT, 'stil', 'hareket', 'kare')
DST = os.path.join(ROOT, 'video', 'public', 'strips')
OUT = os.path.join(ROOT, 'video', 'src', 'characters', 'stripData.ts')

STRIPS = {
    'A01-yuru': 'torso', 'A02-sallan': 'right', 'A03-camciz': 'feet', 'A04-ay': 'feet', 'A05-hizala': 'feet',
    'A06-merak': 'feet', 'A07-elsalla': 'feet', 'A08-sallanma': 'feet', 'A09-okuma': 'feet', 'A10-don': 'feet',
    'A11-yaz': 'feet', 'H01-yaz': 'feet', 'H02-kahve': 'feet', 'H03-gerin': 'feet', 'H04-igne': 'feet',
    'H05-yuru': 'torso', 'H06-defter': 'feet', 'H07-cam': 'feet', 'H08-yorgun': 'feet', 'H09-don': 'feet',
    'H10-elsalla': 'feet', 'H11-defter-goster': 'feet', 'H12-not-yapistir': 'feet',
}
SCALE = 0.76  # standing figures come out ~670 px tall, the same as the old pose cut-outs


def measure(path, mode):
    im = Image.open(path).convert('RGBA')
    w, h = im.size
    px = im.load()
    solid = [[px[x, y][3] > 40 for x in range(w)] for y in range(h)]
    if mode == 'torso':
        y0, y1 = int(h * 0.30), int(h * 0.60)
        xs = [x for y in range(y0, y1) for x in range(w) if solid[y][x]]
    elif mode == 'right':
        xs = [w - 60]
    else:
        y0 = int(h * 0.96)
        xs = [x for y in range(y0, h) for x in range(w) if solid[y][x]]
    ax = round(sum(xs) / max(1, len(xs)))
    return im, w, h, ax, solid


def find_slit(im, solid):
    """The AI's cursor slit: a dark, elongated blob fully inside the head."""
    w, h = im.size
    px = im.load()
    rows = [y for y in range(h) if any(solid[y])]
    top = rows[0]
    limit = min(h, top + 230)
    dark = [[solid[y][x] and px[x, y][3] > 200 and sum(px[x, y][:3]) < 230 for x in range(w)] for y in range(h)]
    seen = set()
    best = None
    for y in range(top, limit):
        for x in range(w):
            if not dark[y][x] or (x, y) in seen:
                continue
            q = deque([(x, y)])
            seen.add((x, y))
            pts = []
            while q:
                cx, cy = q.popleft()
                pts.append((cx, cy))
                for nx, ny in ((cx + 1, cy), (cx - 1, cy), (cx, cy + 1), (cx, cy - 1)):
                    if 0 <= nx < w and top <= ny < limit and dark[ny][nx] and (nx, ny) not in seen:
                        seen.add((nx, ny))
                        q.append((nx, ny))
            xs = [p[0] for p in pts]
            ys = [p[1] for p in pts]
            bw, bh = max(xs) - min(xs) + 1, max(ys) - min(ys) + 1
            if len(pts) < 150 or bh < 28 or bh > 95 or bw > 44:
                continue
            margin = 6
            ok = all(
                0 <= yy < h and 0 <= xx < w and solid[yy][xx]
                for yy in range(min(ys) - margin, max(ys) + margin + 1, 2)
                for xx in range(min(xs) - margin, max(xs) + margin + 1, 2)
            )
            if ok and (best is None or len(pts) > best[0]):
                best = (len(pts), min(xs), min(ys), bw, bh)
    if not best:
        return None
    return {'x': best[1], 'y': best[2], 'w': best[3], 'h': best[4]}


def main():
    os.makedirs(DST, exist_ok=True)
    data = {}
    for name, mode in STRIPS.items():
        sid = name.split('-')[0]
        frames = []
        for i in range(1, 5):
            fn = f'{name}-{i}.png'
            shutil.copyfile(os.path.join(SRC, fn), os.path.join(DST, fn))
            im, w, h, ax, solid = measure(os.path.join(SRC, fn), mode)
            fr = {'file': fn, 'w': w, 'h': h, 'ax': ax}
            if sid.startswith('A'):
                slit = find_slit(im, solid)
                if slit:
                    fr['slit'] = slit
            frames.append(fr)
        data[sid] = {'who': 'ai' if sid.startswith('A') else 'human', 'scale': SCALE, 'frames': frames}
        print(sid, mode, [(f['w'], f['ax'], 'slit' in f) for f in frames])
    lines = [
        '// Generated by video/scripts/make-strips.py from stil/hareket/kare. Do not edit by hand.',
        "export interface StripFrame { file: string; w: number; h: number; ax: number; slit?: { x: number; y: number; w: number; h: number } }",
        "export interface StripMeta { who: 'human' | 'ai'; scale: number; /** Folder under public/. */ dir: 'strips' | 'poses'; frames: StripFrame[] }",
        'export const STRIPS: Record<string, StripMeta> = ' + json.dumps({k: dict(v, dir='strips') for k, v in data.items()}, indent=1) + ';',
        '',
    ]
    with open(OUT, 'w', encoding='utf-8') as f:
        f.write('\n'.join(lines))
    print('wrote', OUT)


if __name__ == '__main__':
    sys.exit(main())
